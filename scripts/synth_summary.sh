#!/usr/bin/env bash
# synth_summary.sh -- builds results/synth/summary.md from the Yosys logs.
# Every number in the table is extracted from a log; nothing is typed in.
set -eu
cd "$(dirname "$0")/.."
R=results/synth

# cell <log> <cell-type regex> : sum of matching cell counts in the final stat
cell() {
    awk '/=== STAT_FINAL ===/{p=1} p' "$1" |
        awk -v re="$2" '$1 ~ "^(" re ")$" {s += $2} END {print s + 0}'
}
total()    { awk '/=== STAT_FINAL ===/{p=1} p && /Number of cells:/ {print $4; exit}' "$1"; }
coarse()   { awk '/=== STAT_COARSE ===/{p=1} /=== STAT_FINAL ===/{p=0} p' "$1" |
                 awk -v re="$2" '$1 ~ "^(" re ")$" {s += $2} END {print s + 0}'; }
depth()    { grep -o 'Longest topological path in alu_top (length=[0-9]*)' "$1" | grep -o '[0-9]*)' | tr -d ')'; }
warns()    { grep -cE '^Warning:' "$1" || true; }

row() { printf '| %s | %s | %s |\n' "$1" "$2" "$3"; }

{
echo "# Synthesis results (generated by scripts/synth_summary.sh)"
echo
echo "Yosys $(yosys -V | awk '{print $2}'), DATA_WIDTH = 10. Behavioral = USE_RCA=0, structural = USE_RCA=1."
echo "Compare columns only within one table; the flows count different kinds of cells."
echo
echo "## Generic gates (\`synth -flatten\`, technology-independent)"
echo
g0=$R/generic_rca0.log; g1=$R/generic_rca1.log
row "Metric" "Behavioral" "Structural (RCA)"
row "---" "---:" "---:"
row "\`\$alu\` cells before techmap" "$(coarse $g0 '\$alu')" "$(coarse $g1 '\$alu')"
row "Total cells" "$(total $g0)" "$(total $g1)"
row "Flip-flops (\`\$_SDFF*\`)" "$(cell $g0 '\$_SDFF.*')" "$(cell $g1 '\$_SDFF.*')"
row "XOR/XNOR" "$(cell $g0 '\$_XN?OR_')" "$(cell $g1 '\$_XN?OR_')"
row "AND/NAND/ANDNOT" "$(cell $g0 '\$_(AND|NAND|ANDNOT)_')" "$(cell $g1 '\$_(AND|NAND|ANDNOT)_')"
row "OR/NOR/ORNOT" "$(cell $g0 '\$_(OR|NOR|ORNOT)_')" "$(cell $g1 '\$_(OR|NOR|ORNOT)_')"
row "MUX" "$(cell $g0 '\$_MUX_')" "$(cell $g1 '\$_MUX_')"
row "NOT" "$(cell $g0 '\$_NOT_')" "$(cell $g1 '\$_NOT_')"
row "Longest path (\`ltp -noff\`, cells)" "$(depth $g0)" "$(depth $g1)"
row "Warnings" "$(warns $g0)" "$(warns $g1)"
echo
echo "## iCE40 mapped (\`synth_ice40\`)"
echo
i0=$R/ice40_rca0.log; i1=$R/ice40_rca1.log
row "Metric" "Behavioral" "Structural (RCA)"
row "---" "---:" "---:"
row "Total cells" "$(total $i0)" "$(total $i1)"
row "SB_LUT4" "$(cell $i0 SB_LUT4)" "$(cell $i1 SB_LUT4)"
row "SB_CARRY" "$(cell $i0 SB_CARRY)" "$(cell $i1 SB_CARRY)"
row "Flip-flops (SB_DFF*)" "$(cell $i0 'SB_DFF.*')" "$(cell $i1 'SB_DFF.*')"
row "Warnings" "$(warns $i0)" "$(warns $i1)"
echo
echo "## Xilinx 7-series mapped (\`synth_xilinx -flatten\`)"
echo
x0=$R/xilinx_rca0.log; x1=$R/xilinx_rca1.log
row "Metric" "Behavioral" "Structural (RCA)"
row "---" "---:" "---:"
row "Total cells" "$(total $x0)" "$(total $x1)"
row "LUT1-LUT6" "$(cell $x0 'LUT[1-6]')" "$(cell $x1 'LUT[1-6]')"
row "CARRY4" "$(cell $x0 CARRY4)" "$(cell $x1 CARRY4)"
row "MUXF7/MUXF8" "$(cell $x0 'MUXF[78]')" "$(cell $x1 'MUXF[78]')"
row "Flip-flops (FDRE)" "$(cell $x0 'FD.*')" "$(cell $x1 'FD.*')"
row "Warnings" "$(warns $x0)" "$(warns $x1)"
echo
echo "## Control: 10-bit adder alone (\`ref_10\` = a+b+cin, \`rca_10\` = ripple_carry_adder)"
echo
a0=$R/adder_ref_10.log; a1=$R/adder_rca_10.log
sect() { awk -v s="=== $2 ===" '$0 ~ s {p=1; next} /^=== [A-Z_]+ ===/ && p {p=0} p' "$1"; }
scell() { sect "$1" "$2" | awk -v re="$3" '$1 ~ "^(" re ")$" {s += $2} END {print s + 0}'; }
stot()  { sect "$1" "$2" | awk '/Number of cells:/ {print $4; exit}'; }
sdep()  { sect "$1" "$2" | grep -o 'length=[0-9]*' | head -n 1 | cut -d= -f2; }
row "Metric" "Behavioral" "Structural (RCA)"
row "---" "---:" "---:"
row "Generic: total cells" "$(stot $a0 STAT_GENERIC)" "$(stot $a1 STAT_GENERIC)"
row "Generic: longest path (cells)" "$(sdep $a0 STAT_GENERIC)" "$(sdep $a1 STAT_GENERIC)"
row "iCE40: SB_LUT4" "$(scell $a0 STAT_ICE40 SB_LUT4)" "$(scell $a1 STAT_ICE40 SB_LUT4)"
row "iCE40: SB_CARRY" "$(scell $a0 STAT_ICE40 SB_CARRY)" "$(scell $a1 STAT_ICE40 SB_CARRY)"
echo
echo "## Where the logic goes: generic cells per unit, hierarchy kept (behavioral)"
echo
echo "Not flattened, so ABC cannot optimize across units and the total exceeds the flattened count."
echo
b=$R/breakdown_rca0.log
row "Unit" "Cells" "Share"
row "---" "---:" "---:"
tot=$(sect $b STAT_HIER | awk '/design hierarchy/ {f=1} f && /Number of cells:/ {print $4; exit}')
for u in alu_arith alu_logic alu_shifter alu_top; do
    n=$(sect $b STAT_HIER | awk -v u="$u" '/^=== / {m = (index($0, u) > 0)} m && /Number of cells:/ {print $4; exit}')
    row "$u" "$n" "$(awk -v n="$n" -v t="$tot" 'BEGIN {printf "%.0f%%", 100 * n / t}')"
done
row "**total**" "$tot" "100%"
} > $R/summary.md
cat $R/summary.md
